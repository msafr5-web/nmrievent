'use strict';
// Guards the bilingual UI: every text key used in a view or a script must exist in Arabic, and every key
// the scripts ask for at runtime must also exist in English (the HTML supplies English only for static text).
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const walk = (d) => fs.readdirSync(path.join(root, d)).flatMap((f) => (f.endsWith('.ejs') ? [path.join(d, f)] : f.includes('.') ? [] : walk(path.join(d, f))));

// Load the dictionary exactly as the browser does.
const sandbox = { document: { documentElement: { lang: 'en' }, querySelectorAll: () => [], getElementById: () => null }, window: {} };
new Function('window', 'document', read('public/js/i18n.js'))(sandbox.window, sandbox.document);
const { en: EN, ar: AR } = sandbox.window.NMR.dict;

const viewKeys = new Set(walk('views').flatMap((f) => [...read(f).matchAll(/data-i18n="([^"]+)"/g)].map((m) => m[1])));
// keys printed through EJS expressions: data-i18n="<%= s[1] %>" etc. are built from literals in the same file
const ejsLiterals = new Set(walk('views').flatMap((f) => [...read(f).matchAll(/'((?:nav|hero|stat|services|common|pf|cat|cta)\.[\w.]+)'/g)].map((m) => m[1])));

test('every static key has an Arabic translation', () => {
  const missing = [...viewKeys].filter((k) => !k.includes('<%') && !AR[k]);
  assert.deepEqual(missing, []);
});

test('keys generated by EJS loops are translated too', () => {
  const missing = [...ejsLiterals].filter((k) => !AR[k]);
  assert.deepEqual(missing, []);
  // service and module keys are assembled as s.<id>.t / s.<id>.d and mod.<id>.t / mod.<id>.d
  for (const id of ['graphic', 'd3', 'print', 'event']) for (const s of ['t', 'd']) assert.ok(AR[`s.${id}.${s}`], `s.${id}.${s}`);
  for (const id of ['booth', 'compliance', 'crowd', 'crew']) for (const s of ['t', 'd']) assert.ok(AR[`mod.${id}.${s}`], `mod.${id}.${s}`);
});

test('keys requested at runtime exist in both languages', () => {
  const scripts = fs.readdirSync(path.join(root, 'public/js')).filter((f) => f.endsWith('.js') && f !== 'i18n.js');
  const literal = new Set(); const prefixes = new Set();
  for (const f of scripts) {
    const src = read(`public/js/${f}`);
    for (const m of src.matchAll(/\bt\('([\w.]+)'\s*[,)]/g)) literal.add(m[1]);
    for (const m of src.matchAll(/\bt\('([\w.]+\.)'\s*\+/g)) prefixes.add(m[1]);
  }
  const missing = [...literal].filter((k) => !(k in EN) || !(k in AR));
  assert.deepEqual(missing, []);
  const need = {
    'role.': ['EVENT_DIRECTOR', 'ZONE_SUPERVISOR', 'SAFETY', 'USHER', 'FIRST_AID'],
    'level.': ['normal', 'busy', 'near', 'over', 'unknown'],
    'status.': ['COMPLIANT', 'CONDITIONAL', 'NON_COMPLIANT', 'PLANNED', 'ACTIVE', 'ON_BREAK', 'OFF_DUTY'],
    'band.': ['overcrowded', 'tight', 'standard', 'comfortable'],
    'flame.': ['booth_fabrics', 'drapes_banners', 'wood_panels', 'foam_graphics', 'carpets'],
    'auth.': ['SECA', 'GEA', 'CIVIL_DEFENSE'],
    'cat.': ['exhibition', 'event', 'interior', 'branding'],
    'f.': ['OVER_MAX_CAPACITY', 'OVER_SELECTED_DENSITY', 'OUTDOOR_HEAT_PLAN', 'SPRINKLERS_REQUIRED', 'LONG_DURATION'],
    'p.': require('../src/utils/compliance').calculateCompliance({ area: 5000, crowd: 600, venueType: 'OUTDOOR', eventType: 'exhibition', density: 2, duration: 1 }).permits
      .concat(require('../src/utils/compliance').calculateCompliance({ area: 5000, crowd: 600, venueType: 'INDOOR', eventType: 'entertainment', density: 2, duration: 1 }).permits)
      .flatMap((p) => p.items.map((i) => i.id)),
  };
  for (const [prefix, ids] of Object.entries(need)) {
    assert.ok(prefixes.has(prefix) || prefix === 'f.' || prefix === 'status.', `script uses prefix ${prefix}`);
    for (const id of ids) { assert.ok(EN[prefix + id], `EN ${prefix}${id}`); assert.ok(AR[prefix + id], `AR ${prefix}${id}`); }
  }
  for (const code of ['VALIDATION_ERROR', 'ALREADY_REGISTERED', 'OTP_COOLDOWN', 'INVALID_OTP', 'OTP_LOCKED', 'RATE_LIMITED', 'UNAUTHORIZED', 'ADMIN_DISABLED', 'ALREADY_VERIFIED', 'NOT_FOUND']) {
    assert.ok(EN[`err.${code}`] && AR[`err.${code}`], `err.${code}`);
  }
});

test('placeholders match between English and Arabic', () => {
  const vars = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join();
  for (const k of Object.keys(AR)) if (EN[k]) assert.equal(vars(AR[k]), vars(EN[k]), k);
});
